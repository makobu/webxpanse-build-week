-- Imported demo models could all remain active after losing their identities.
-- Keep the newest model active for each workspace/type, while older rows remain
-- available for comparison and audit.
UPDATE ml_models older
JOIN ml_models newer
  ON newer.workspace_id = older.workspace_id
 AND newer.model_type = older.model_type
 AND (
      newer.trained_at > older.trained_at
      OR (newer.trained_at = older.trained_at AND newer.id > older.id)
 )
SET older.is_active = 0
WHERE older.is_active = 1;
