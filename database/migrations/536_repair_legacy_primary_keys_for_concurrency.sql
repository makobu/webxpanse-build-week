-- Repair legacy/imported tables whose original PRIMARY KEY / AUTO_INCREMENT
-- constraints were lost. Missing identities caused non-strict MariaDB sessions to
-- silently write repeated id=0 rows, which is unsafe for concurrent requests.
--
-- MariaDB resequences zero-valued rows when PRIMARY KEY + AUTO_INCREMENT are
-- added in one ALTER. The only positive duplicate found in supported legacy
-- schemas is the global deal_automation_config singleton, so retain its newest row.
--
-- Derived ML cache rows with model_id=0 cannot be reliably linked back to one of
-- several legacy model rows. Remove only those invalid derived rows because they are
-- regenerated by the scoring runtime. Source models and CRM records are kept.

SET @repair_deal_config_has_pk := (
    SELECT COUNT(*)
    FROM information_schema.TABLE_CONSTRAINTS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'deal_automation_config'
      AND CONSTRAINT_TYPE = 'PRIMARY KEY'
);
SET @repair_deal_config_delete_count := (
    SELECT GREATEST(COUNT(*) - 1, 0)
    FROM deal_automation_config
);
SET @repair_primary_sql := IF(
    @repair_deal_config_has_pk = 0 AND @repair_deal_config_delete_count > 0,
    CONCAT(
        'DELETE FROM deal_automation_config ',
        'ORDER BY updated_at ASC LIMIT ',
        @repair_deal_config_delete_count
    ),
    'SELECT 1'
);
PREPARE repair_primary_stmt FROM @repair_primary_sql;
EXECUTE repair_primary_stmt;
DEALLOCATE PREPARE repair_primary_stmt;

