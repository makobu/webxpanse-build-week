CREATE TABLE IF NOT EXISTS marketing_conversion_events (
    id INT PRIMARY KEY AUTO_INCREMENT,
    workspace_id INT NOT NULL,
    landing_page_id INT NULL,
    visitor_session_id INT NULL,
    tracking_event_id INT NULL,
    form_id INT NULL,
    contact_id INT NULL,
    deal_id INT NULL,
    uuid CHAR(36) NOT NULL,
    conversion_type ENUM('form_submit','lead_capture','demo_request','download','newsletter_signup','event_registration','contact_request','custom') NOT NULL DEFAULT 'lead_capture',
    conversion_value DECIMAL(12,2) NULL,
    metadata_json JSON NULL,
    occurred_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uniq_marketing_conversion_events_uuid (uuid),
    KEY idx_marketing_conversion_events_workspace_type (workspace_id, conversion_type, occurred_at),
    KEY idx_marketing_conversion_events_workspace_landing (workspace_id, landing_page_id, occurred_at),
    KEY idx_marketing_conversion_events_workspace_contact (workspace_id, contact_id, occurred_at),
    CONSTRAINT fk_marketing_conversion_events_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE CASCADE,
    CONSTRAINT fk_marketing_conversion_events_landing FOREIGN KEY (landing_page_id) REFERENCES marketing_landing_pages(id) ON DELETE SET NULL,
    CONSTRAINT fk_marketing_conversion_events_session FOREIGN KEY (visitor_session_id) REFERENCES marketing_visitor_sessions(id) ON DELETE SET NULL,
    CONSTRAINT fk_marketing_conversion_events_event FOREIGN KEY (tracking_event_id) REFERENCES marketing_tracking_events(id) ON DELETE SET NULL,
    CONSTRAINT fk_marketing_conversion_events_form FOREIGN KEY (form_id) REFERENCES forms(id) ON DELETE SET NULL,
    CONSTRAINT fk_marketing_conversion_events_contact FOREIGN KEY (contact_id) REFERENCES contacts(id) ON DELETE SET NULL,
    CONSTRAINT fk_marketing_conversion_events_deal FOREIGN KEY (deal_id) REFERENCES deals(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
