-- Marketing Phase 43: experimentation and A/B testing.

CREATE TABLE IF NOT EXISTS marketing_experiments (
    id INT PRIMARY KEY AUTO_INCREMENT,
    workspace_id INT NOT NULL,
    uuid CHAR(36) NOT NULL,
    title VARCHAR(180) NOT NULL,
    experiment_type ENUM('landing_page','email','cta','offer','ad_copy','content_format','channel_bundle','other') NOT NULL DEFAULT 'other',
    hypothesis TEXT NULL,
    success_metric VARCHAR(120) NOT NULL DEFAULT 'conversion_rate',
    status ENUM('draft','running','paused','completed','archived') NOT NULL DEFAULT 'draft',
    content_item_id INT NULL,
    landing_page_id INT NULL,
    email_run_id INT NULL,
    channel_export_bundle_id INT NULL,
    campaign_id INT NULL,
    winner_variant_id INT NULL,
    start_date DATE NULL,
    end_date DATE NULL,
    metadata_json JSON NULL,
    owner_user_id INT NULL,
    created_by INT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uniq_marketing_experiments_uuid (uuid),
    KEY idx_marketing_experiments_workspace_status (workspace_id, status, experiment_type),
    KEY idx_marketing_experiments_workspace_campaign (workspace_id, campaign_id),
    CONSTRAINT fk_marketing_experiments_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE CASCADE,
    CONSTRAINT fk_marketing_experiments_owner FOREIGN KEY (owner_user_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_marketing_experiments_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS marketing_experiment_variants (
    id INT PRIMARY KEY AUTO_INCREMENT,
    workspace_id INT NOT NULL,
    experiment_id INT NOT NULL,
    uuid CHAR(36) NOT NULL,
    variant_key VARCHAR(80) NOT NULL,
    name VARCHAR(180) NOT NULL,
    description TEXT NULL,
    payload_json JSON NULL,
    traffic_weight DECIMAL(5,2) NOT NULL DEFAULT 50.00,
    status ENUM('draft','active','paused','winner','archived') NOT NULL DEFAULT 'draft',
    created_by INT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uniq_marketing_experiment_variants_uuid (uuid),
    UNIQUE KEY uniq_marketing_experiment_variant_key (workspace_id, experiment_id, variant_key),
    KEY idx_marketing_experiment_variants_workspace_experiment (workspace_id, experiment_id, status),
    CONSTRAINT fk_marketing_experiment_variants_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE CASCADE,
    CONSTRAINT fk_marketing_experiment_variants_experiment FOREIGN KEY (experiment_id) REFERENCES marketing_experiments(id) ON DELETE CASCADE,
    CONSTRAINT fk_marketing_experiment_variants_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS marketing_experiment_results (
    id INT PRIMARY KEY AUTO_INCREMENT,
    workspace_id INT NOT NULL,
    experiment_id INT NOT NULL,
    variant_id INT NOT NULL,
    uuid CHAR(36) NOT NULL,
    metric_name VARCHAR(120) NOT NULL,
    metric_value DECIMAL(14,4) NOT NULL DEFAULT 0.0000,
    sample_size INT NOT NULL DEFAULT 0,
    observed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    metadata_json JSON NULL,
    created_by INT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uniq_marketing_experiment_results_uuid (uuid),
    KEY idx_marketing_experiment_results_workspace_experiment (workspace_id, experiment_id, metric_name),
    KEY idx_marketing_experiment_results_workspace_variant (workspace_id, variant_id, observed_at),
    CONSTRAINT fk_marketing_experiment_results_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces(id) ON DELETE CASCADE,
    CONSTRAINT fk_marketing_experiment_results_experiment FOREIGN KEY (experiment_id) REFERENCES marketing_experiments(id) ON DELETE CASCADE,
    CONSTRAINT fk_marketing_experiment_results_variant FOREIGN KEY (variant_id) REFERENCES marketing_experiment_variants(id) ON DELETE CASCADE,
    CONSTRAINT fk_marketing_experiment_results_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
